/*
ROLES DE APLICACION
PRINCIPIO DE MINIMO PRIVILEGIO
LOS ROLES SE CREAN CON LOGIN Y CONTRASEÑA EN db/security/bootstrap_seguridad.sql
(SE EJECUTA ANTES DE LA PRIMERA MIGRACION)
ESTA MIGRACION SOLO DECLARA SUS PRIVILEGIOS
*/

GRANT USAGE
ON SCHEMA public
TO app_admin, app_migrator, app_rw, app_ro;

GRANT
SELECT,
INSERT,
UPDATE,
DELETE
ON ALL TABLES IN SCHEMA public
TO app_rw;

GRANT
USAGE,
SELECT
ON ALL SEQUENCES IN SCHEMA public
TO app_rw;

GRANT SELECT
ON ALL TABLES IN SCHEMA public
TO app_ro;

GRANT SELECT
ON ALL SEQUENCES IN SCHEMA public
TO app_ro;

GRANT EXECUTE
ON ALL FUNCTIONS IN SCHEMA public
TO app_rw;

/*
PERMISOS FUTUROS
OBJETOS CREADOS POR EL ROL QUE EJECUTA MIGRACIONES
*/

ALTER DEFAULT PRIVILEGES
IN SCHEMA public
GRANT SELECT, INSERT, UPDATE, DELETE
ON TABLES
TO app_rw;

ALTER DEFAULT PRIVILEGES
IN SCHEMA public
GRANT USAGE, SELECT
ON SEQUENCES
TO app_rw;

ALTER DEFAULT PRIVILEGES
IN SCHEMA public
GRANT SELECT
ON TABLES
TO app_ro;

ALTER DEFAULT PRIVILEGES
IN SCHEMA public
GRANT SELECT
ON SEQUENCES
TO app_ro;

ALTER DEFAULT PRIVILEGES
IN SCHEMA public
GRANT EXECUTE
ON FUNCTIONS
TO app_rw;

